// じゃらんの検索キーワードは Shift_JIS でURLに入れる必要があるので、ブラウザの文字コード変換を使って作る
let SJIS_TABLE = null;
function sjisPercent(text) {
  if (!SJIS_TABLE) {
    SJIS_TABLE = {};
    const dec = new TextDecoder("shift_jis");
    for (let hi = 0x81; hi <= 0xfc; hi++) {
      if (hi > 0x9f && hi < 0xe0) continue;
      for (let lo = 0x40; lo <= 0xfc; lo++) {
        if (lo === 0x7f) continue;
        const ch = dec.decode(new Uint8Array([hi, lo]));
        if (ch.length === 1 && ch !== "�" && !(ch in SJIS_TABLE)) SJIS_TABLE[ch] = [hi, lo];
      }
    }
    for (let b = 0xa1; b <= 0xdf; b++) SJIS_TABLE[dec.decode(new Uint8Array([b]))] = [b];
  }
  return [...text].map((ch) => {
    if (ch.charCodeAt(0) < 0x80) return encodeURIComponent(ch);
    return (SJIS_TABLE[ch] || []).map((b) => "%" + b.toString(16).toUpperCase().padStart(2, "0")).join("");
  }).join("");
}
