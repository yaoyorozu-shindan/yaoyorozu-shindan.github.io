// 旧暦の各月1日の宿（SUKUYO の番号）：1月=室 2月=奎 3月=胃 4月=畢 5月=参 6月=鬼 7月=張 8月=角 9月=氐 10月=心 11月=斗 12月=虚
const SUKUYO_MONTH_START = { 1: 22, 2: 24, 3: 26, 4: 1, 5: 3, 6: 5, 7: 8, 8: 11, 9: 13, 10: 15, 11: 18, 12: 20 };

// birthday "YYYY-MM-DD" → { index, lunar, ...SUKUYO[index] }
function sukuyoOf(birthday) {
  const [y, m, d] = birthday.split("-").map(Number);
  const lunar = toLunar(y, m, d, 9);
  const index = (SUKUYO_MONTH_START[lunar.month] + lunar.day - 1) % 27;
  return { index, lunar, ...SUKUYO[index] };
}

// 三九の秘法：自分の宿から相手の宿まで何番目か → 自分から見た関係
const SUKUYO_STEP = ["命", "栄", "衰", "安", "危", "成", "壊", "友", "親"];
function sukuyoRelation(a, b) {
  const dist = (b.index - a.index + 27) % 27;
  if (dist === 0) return "命";
  if (dist === 9) return "業"; // 自分から見て相手が「業」、相手から見て自分が「胎」
  if (dist === 18) return "胎";
  return SUKUYO_STEP[dist % 9];
}

