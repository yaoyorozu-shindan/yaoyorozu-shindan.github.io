const YAO_NAMES = ["初爻", "二爻", "三爻", "四爻", "五爻", "上爻"];

// 今日の易：保存済みなら返し、まだなら null
function ekiToday(dateStr) {
  try {
    const saved = JSON.parse(localStorage.getItem("eki") || "null");
    if (saved && saved.date === dateStr) return saved;
  } catch (e) {}
  return null;
}
// 引く：その場でランダムに卦（0〜63）と動く爻（0〜5）を決めて保存
function ekiDraw(dateStr) {
  const r = new Uint32Array(2);
  (window.crypto || window.msCrypto).getRandomValues(r);
  const res = { date: dateStr, hex: r[0] % 64, line: r[1] % 6 };
  try { localStorage.setItem("eki", JSON.stringify(res)); } catch (e) {}
  return res;
}

// 卦の6本の線（下から）。動く爻は印をつける
function hexLines(h) {
  const [, , upper, lower] = HEXAGRAMS[h];
  return [...TRIGRAMS[lower].lines, ...TRIGRAMS[upper].lines];
}

// ---- 画面 ----
function ekiCardHTML() {
  const s = ekiToday(todayString());
  return `<div class="card eki-card" id="eki-card">${s ? ekiResultHTML(s) : ekiButtonHTML()}</div>`;
}
function ekiButtonHTML() {
  return `<h3>☯ 今日の易</h3>
    <p><a href="articles/eki.html">卦と金色の線の読み方</a></p>
    <p>心を静めて、今日いちばん気になることを思い浮かべてから押してください。易は一日一回。引いた卦は今日いっぱい変わりません。</p>
    <button type="button" id="eki-draw" class="eki-btn">☯ 今日の易を引く</button>`;
}
function ekiResultHTML(s, fresh) {
  const [name, read, upper, lower, key, text, yao] = HEXAGRAMS[s.hex];
  const lines = hexLines(s.hex);
  // 上の線から順に描く（易の線は下から数えるので逆順）
  const bars = lines.map((v, i) => `<span class="eki-bar ${v ? "yang" : "yin"}${i === s.line ? " moving" : ""}"></span>`).reverse().join("");
  return `<h3>☯ 今日の易</h3>
    <p><a href="articles/eki.html">卦と金色の線の読み方</a></p>
    <div class="eki-result${fresh ? " fresh" : ""}">
      <div class="eki-hex" aria-hidden="true">${bars}</div>
      <p class="eki-name"><ruby>${name}<rt>${read}</rt></ruby></p>
      <p class="eki-sub">第${s.hex + 1}卦・${TRIGRAMS[upper].image}（${upper}）の下に${TRIGRAMS[lower].image}（${lower}）・「${key}」</p>
      <p>${text}</p>
      <p class="eki-yao"><b>✨ ${YAO_NAMES[s.line]}が動く：</b>${yao[s.line]}</p>
      <p class="note">金色の線が、今日動いている爻（こう）です。易は一日一回。明日また引いてみてください。</p>
    </div>`;
}
// 「引く」ボタン（結果の画面は作り直されるので、ページ全体で受け取る）
document.addEventListener("click", (e) => {
  if (!e.target.closest("#eki-draw")) return;
  const s = ekiToday(todayString()) || ekiDraw(todayString());
  document.getElementById("eki-card").innerHTML = ekiResultHTML(s, true);
});
